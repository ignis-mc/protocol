// interopContentKey is the content key announced for the keyed test pack.
// The pack is not actually encrypted: clients only store the key.
const interopContentKey = "interop0content0key0123456789abc"

// generatedPack describes a test pack built at start-up.
type generatedPack struct {
	file   string
	uuid   string
	name   string
	filler int
	key    string
}

var generatedPacks = []generatedPack{
	{file: "small.mcpack", uuid: "6d1b9a31-3f0c-4c55-9a27-6f1e3a000001", name: "Interop Small"},
	{file: "large.mcpack", uuid: "6d1b9a31-3f0c-4c55-9a27-6f1e3a000002", name: "Interop Large", filler: 3_500_000},
	{file: "keyed.mcpack", uuid: "6d1b9a31-3f0c-4c55-9a27-6f1e3a000003", name: "Interop Keyed", filler: 20_000, key: interopContentKey},
}

// urlPack is served over HTTPS and offered with a download URL.
var urlPack = generatedPack{file: "url.mcpack", uuid: "6d1b9a31-3f0c-4c55-9a27-6f1e3a000004", name: "Interop URL", filler: 300_000}

// writePack writes a resource pack archive: a deflated manifest inside a
// folder (as packs from the marketplace are laid out) and a stored file of
// pseudo-random, incompressible filler.
func writePack(path string, p generatedPack) error {
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	manifest := fmt.Sprintf(`{
  // generated by interop/dragonfly
  "format_version": 2,
  "header": {
    "name": %q,
    "description": "protocol interop test pack",
    "uuid": %q,
    "version": [1, 0, 0],
    "min_engine_version": [1, 21, 0] /* gophertunnel's jsonc rejects trailing commas */
  },
  # hash comments are jsonc too
  "modules": [{"type": "resources", "uuid": "%s", "version": [1, 0, 0]}]
}
`, p.name, p.uuid, strings.Replace(p.uuid, "6d1b", "7e2c", 1))
	f, err := w.Create(p.name + "/manifest.json")
	if err != nil {
		return err
	}
	if _, err := f.Write([]byte(manifest)); err != nil {
		return err
	}
	if p.filler > 0 {
		f, err := w.CreateHeader(&zip.FileHeader{Name: p.name + "/textures/filler.bin", Method: zip.Store})
		if err != nil {
			return err
		}
		data := make([]byte, p.filler)
		r := mrand.NewChaCha8([32]byte{byte(len(p.name)), byte(p.filler)})
		_, _ = r.Read(data)
		if _, err := f.Write(data); err != nil {
			return err
		}
	}
	if err := w.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

// loadPacks builds the generated packs in dir and loads them together with
// the archives or directories in extra. With serveURL it also serves one
// pack over HTTPS and loads it by URL, writing the CA certificate the
// client must trust to certOut.
func loadPacks(dir string, extra []string, serveURL bool, certOut string) ([]*resource.Pack, error) {
	var packs []*resource.Pack
	for _, g := range generatedPacks {
		path := filepath.Join(dir, g.file)
		if err := writePack(path, g); err != nil {
			return nil, fmt.Errorf("write %v: %w", g.file, err)
		}
		pack, err := resource.ReadPath(path)
		if err != nil {
			return nil, fmt.Errorf("read %v: %w", g.file, err)
		}
		if g.key != "" {
			pack = pack.WithContentKey(g.key)
		}
		packs = append(packs, pack)
	}
	for _, path := range extra {
		pack, err := resource.ReadPath(path)
		if err != nil {
			return nil, fmt.Errorf("read %v: %w", path, err)
		}
		packs = append(packs, pack)
	}
	if serveURL {
		pack, err := servePackURL(dir, certOut)
		if err != nil {
			return nil, fmt.Errorf("serve pack by URL: %w", err)
		}
		packs = append(packs, pack)
	}
	for _, p := range packs {
		sum := p.Checksum()
		key, url := p.ContentKey(), p.DownloadURL()
		if key == "" {
			key = "-"
		}
		if url == "" {
			url = "-"
		}
		fmt.Printf("SERVING %v %v %v %v key=%v url=%v\n", p.UUID(), p.Version(), p.Len(), hex.EncodeToString(sum[:]), key, url)
	}
	return packs, nil
}

// servePackURL serves urlPack at https://127.0.0.1:<port>/url.mcpack with a
// certificate from a fresh CA and returns the pack read back from that URL,
// so its DownloadURL is set.
func servePackURL(dir, certOut string) (*resource.Pack, error) {
	path := filepath.Join(dir, urlPack.file)
	if err := writePack(path, urlPack); err != nil {
		return nil, err
	}
	caKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, err
	}
	now := time.Now()
	caTemplate := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: "protocol interop CA"},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(24 * time.Hour),
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	caDER, err := x509.CreateCertificate(rand.Reader, caTemplate, caTemplate, &caKey.PublicKey, caKey)
	if err != nil {
		return nil, err
	}
	ca, _ := x509.ParseCertificate(caDER)
	leafKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, err
	}
	leafTemplate := &x509.Certificate{
		SerialNumber: big.NewInt(2),
		Subject:      pkix.Name{CommonName: "127.0.0.1"},
		NotBefore:    now.Add(-time.Hour),
		NotAfter:     now.Add(24 * time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		IPAddresses:  []net.IP{net.IPv4(127, 0, 0, 1)},
	}
	leafDER, err := x509.CreateCertificate(rand.Reader, leafTemplate, ca, &leafKey.PublicKey, caKey)
	if err != nil {
		return nil, err
	}
	caPEM := pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: caDER})
	if err := os.WriteFile(certOut, caPEM, 0o644); err != nil {
		return nil, err
	}

	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return nil, err
	}
	mux := http.NewServeMux()
	content, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	mux.HandleFunc("/"+urlPack.file, func(w http.ResponseWriter, r *http.Request) {
		fmt.Println("HTTP GET", r.URL.Path, r.UserAgent())
		http.ServeContent(w, r, urlPack.file, time.Time{}, bytes.NewReader(content))
	})
	srv := &http.Server{
		Handler: mux,
		TLSConfig: &tls.Config{Certificates: []tls.Certificate{{
			Certificate: [][]byte{leafDER, caDER},
			PrivateKey:  leafKey,
		}}},
	}
	go func() { _ = srv.ServeTLS(ln, "", "") }()

	// resource.ReadURL uses http.Get: trust the CA for that one download.
	pool := x509.NewCertPool()
	pool.AddCert(ca)
	http.DefaultTransport.(*http.Transport).TLSClientConfig = &tls.Config{RootCAs: pool}
	return resource.ReadURL(fmt.Sprintf("https://%v/%v", ln.Addr(), urlPack.file))
}
